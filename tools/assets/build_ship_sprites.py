#!/usr/bin/env python3
"""Convert the generated ship sheet into compact 1-bit class sprites."""

from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets" / "source" / "ship-class-sheet.png"
OUTPUT = ROOT / "img_ship_classes.h"

SPRITES = [
    ("SLOOP", (35, 315, 235, 600), 46, 42),
    ("SCHOONER", (245, 285, 585, 600), 54, 42),
    ("BRIG", (565, 240, 925, 600), 60, 46),
    ("PACKET", (925, 210, 1285, 600), 68, 48),
    ("INDIAMAN", (1260, 190, 1710, 600), 78, 52),
]


def foreground_mask(image: Image.Image) -> Image.Image:
    pixels = image.convert("RGB")
    mask = Image.new("L", pixels.size, 0)
    out = []
    for r, g, b in pixels.getdata():
        # The generated sheet has a baked checkerboard background. Ship paint
        # and ink are sufficiently chromatic or dark to separate cleanly.
        background = min(r, g, b) > 205 and max(r, g, b) - min(r, g, b) < 24
        out.append(0 if background else 255)
    mask.putdata(out)
    return mask


def fit_sprite(mask: Image.Image, width: int, height: int) -> Image.Image:
    bounds = mask.getbbox()
    if not bounds:
        return Image.new("1", (width, height), 0)
    cropped = mask.crop(bounds)
    scale = min(width / cropped.width, height / cropped.height)
    resized = cropped.resize(
        (max(1, round(cropped.width * scale)), max(1, round(cropped.height * scale))),
        Image.Resampling.LANCZOS,
    ).point(lambda value: 255 if value >= 96 else 0)
    result = Image.new("1", (width, height), 0)
    x = (width - resized.width) // 2
    y = height - resized.height - 1
    result.paste(resized, (x, y))
    return result


def emit(name: str, image: Image.Image) -> str:
    width, height = image.size
    row_bytes = (width + 7) // 8
    values = []
    for y in range(height):
        for byte in range(row_bytes):
            value = 0
            for bit in range(8):
                x = byte * 8 + bit
                if x < width and image.getpixel((x, y)):
                    value |= 0x80 >> bit
            values.append(value)
    lines = []
    for offset in range(0, len(values), 16):
        lines.append("  " + ", ".join(str(v) for v in values[offset:offset + 16]) + ",")
    return (
        f"static constexpr int SHIP_{name}_W = {width};\n"
        f"static constexpr int SHIP_{name}_H = {height};\n"
        f"static const uint8_t SHIP_{name}_DATA[{len(values)}] = {{\n"
        + "\n".join(lines)
        + "\n};\n"
    )


def main() -> None:
    source = Image.open(SOURCE)
    mask = foreground_mask(source)
    parts = []
    for name, bounds, width, height in SPRITES:
        sprite = fit_sprite(mask.crop(bounds), width, height)
        parts.append(emit(name, sprite))

    OUTPUT.write_text(
        "// Generated by tools/assets/build_ship_sprites.py. Do not edit by hand.\n"
        "#pragma once\n#include <stdint.h>\n\n"
        + "\n".join(parts),
        encoding="ascii",
    )
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
